const u8* glyph8x8(char c) noexcept {
    unsigned u = static_cast<unsigned char>(c);
    if (u >= 'a' && u <= 'z') u -= 32;            // lowercase -> uppercase
    if (u < 0x20 || u > 0x5F) return kSpace;       // outside the covered block
    return kFont[u - 0x20];
}

