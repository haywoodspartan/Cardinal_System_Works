int g_checks = 0, g_fail = 0;
void chk(bool ok, const char* e, int line) {
    ++g_checks;
    if (!ok) { ++g_fail; cardinal::log::errorf("ztest", "FAIL  L%d  %s", line, e); }
}
#define CHECK(x) ::chk(static_cast<bool>(x), #x, __LINE__)

