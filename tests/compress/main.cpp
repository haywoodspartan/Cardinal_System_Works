// =============================================================================
// Cardinal — DEFLATE inflate regression suite (cardinal::core::compress).
//
// The hand-rolled inflate is the keystone for FBX (compressed arrays), USDZ
// (deflated zip entries) and a real PNG decoder, and it is the highest-bug-
// density code in the import effort, so it is pinned against REAL compressed
// vectors produced by .NET's DeflateStream/ZLibStream (a known-good encoder):
//   * FIXED-Huffman   block (small repetitive input)
//   * DYNAMIC-Huffman block (large varied input — the most complex path)
//   * STORED          block (hand-built, no compression)
//   * zlib wrapper    (RFC 1950 header + adler trailer)
//   * failure paths   (bad header, truncation, output overflow, null)
// Zero deps; the expected outputs are reconstructed in-code, not shipped.
// =============================================================================

